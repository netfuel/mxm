"""Write assets/videos.js from tracks.json + whatever is encoded in media/.
Tracks without an encode point at the placeholder (first encoded track, Wings preferred)."""
import json, os
site = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tracks = json.load(open(os.path.join(site, "tools", "tracks.json")))
done = lambda s: os.path.isfile(os.path.join(site, "media", s, "1080.mp4"))
ready = [t["slug"] for t in tracks if done(t["slug"])]
fallback = "MarceauxMarceaux-Wings" if "MarceauxMarceaux-Wings" in ready else (ready[0] if ready else "MarceauxMarceaux-Wings")
out = []
for t in tracks:
    src = t["slug"] if done(t["slug"]) else fallback
    out.append({**t, "media": src, "placeholder": src != t["slug"]})
os.makedirs(os.path.join(site, "public", "assets"), exist_ok=True)
with open(os.path.join(site, "public", "assets", "videos.js"), "w") as fh:
    fh.write("// Generated by tools/manifest.py. Do not edit by hand.\nwindow.VIDEOS = ")
    json.dump(out, fh, indent=1)
    fh.write(";\n")
print(f"videos.js: {len(ready)} encoded, {len(out)-len(ready)} using placeholder ({fallback})")
